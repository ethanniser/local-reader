import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
const extractor=readFileSync(new URL('extension/extract-article.js',root),'utf8');
const background=readFileSync(new URL('extension/background.js',root),'utf8');
const start=background.indexOf('function capturePage() {');
const end=background.indexOf('\nasync function captureDraft(',start);
if(start<0||end<0)throw new Error('Cannot locate reviewed capturePage extractor');
const wrapper=`\nvar ExtensionPreprocessingJS = {run: function(context) {
  try {
    const captured=capturePage();
    if(captured.error){context.completionFunction({error:captured.error});return;}
    const words=captured.words||captured.text.trim().split(/\\s+/);
    const article={title:captured.title,source:captured.source,words,paragraphs:captured.paragraphs||[{start:0,end:words.length,kind:'paragraph'}],marks:captured.marks||[],images:captured.images||[],tags:[],position:0};
    while(article.images.length&&JSON.stringify(article).length>4500000)article.images.pop();
    context.completionFunction({article});
  }catch(error){context.completionFunction({error:'Could not read this page. Share selected text instead.'});}
}};\n`;
writeFileSync(new URL('ios/ShareExtension/Preprocess.js',root),'// Generated by ios/prepare-share.mjs from the reviewed Chrome/Safari extractors.\n'+extractor+'\n'+background.slice(start,end)+wrapper);
